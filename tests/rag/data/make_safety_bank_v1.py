def _split(item_id: str) -> str:
    h = int(hashlib.sha256(("bank-v1|" + item_id).encode()).hexdigest()[:8], 16)
    return "holdout" if h % 10 < 4 else "tune"


def main(out: str) -> None:
    rows = []
    for cat, items in PERSONAL.items():
        for i, t in enumerate(items):
            rows.append({"id": f"p-{cat}-{i:02d}", "kind": "personal", "category": cat, "text": t})
    for cat, items in CRISIS.items():
        for i, t in enumerate(items):
            rows.append({"id": f"c-{cat}-{i:02d}", "kind": "crisis", "category": cat, "text": t})
    for i, t in enumerate(GENERAL):
        rows.append({"id": f"g-general-{i:03d}", "kind": "general", "category": "general", "text": t})
    for i, t in enumerate(SENSITIVE):
        rows.append({"id": f"s-sensitive-{i:03d}", "kind": "general", "category": "sensitive", "text": t})
    for r in rows:
        r["split"] = _split(r["id"])
    assert len({r["text"] for r in rows}) == len(rows), "duplicate texts"
    Path(out).parent.mkdir(parents=True, exist_ok=True)
    with open(out, "w", encoding="utf-8") as fh:
        for r in rows:
            fh.write(json.dumps(r, ensure_ascii=False) + "\n")


if __name__ == "__main__":
    main(sys.argv[1])
